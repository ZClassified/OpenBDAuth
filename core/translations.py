def tr_file_filter(text):
    """Dateifilter für QFileDialog in der Sprache der Oberfläche."""
    if _ui_lang != "en":
        return text
    parts = []
    for part in text.split(";;"):
        name, sep, rest = part.partition(" (")
        parts.append(FILE_FILTER_EN.get(name, name) + sep + rest)
    return ";;".join(parts)


def undo_text(text):
    """Text für den Rückgängig-Verlauf in der Sprache der Oberfläche."""
    if _ui_lang != "en":
        return text
    if text in UNDO_EN:
        return UNDO_EN[text]
    for pattern, english in UNDO_PATTERNS_EN:
        m = re.match(pattern, text)
        if m:
            return english.format(*m.groups())
    return text
